import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { createRequire } from 'node:module';
import { serviceIconPresets, automaticIconKeys } from '../src/lib/service-icons.mjs';
const require = createRequire(import.meta.url);
const React = require('react'), { renderToStaticMarkup } = require('react-dom/server');
const icons = require('lucide-react'), sharp = require('sharp');
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const mobile = path.resolve(root, '../Taskly-main');
const names = { cleaning:'Brush', sparkles:'Sparkles', sofa:'Sofa', bed:'BedDouble', aircon:'AirVent', repair:'Wrench', laundry:'WashingMachine', kitchen:'CookingPot', assembly:'Hammer', moving:'Truck', packing:'Package', shopping:'ShoppingBag', pets:'PawPrint', computer:'Monitor', wifi:'Wifi', iron:'Shirt', grid:'LayoutGrid' };
const webAssets = path.join(root, 'public/service-icons'), appAssets = path.join(mobile, 'assets/service-icons');
await fs.mkdir(webAssets, { recursive:true }); await fs.mkdir(appAssets, { recursive:true });
for (const {key} of serviceIconPresets) {
  const svg = renderToStaticMarkup(React.createElement(icons[names[key]], {size:160, color:'#109f87', strokeWidth:2}));
  const png = await sharp(Buffer.from(svg)).png().toBuffer();
  await fs.writeFile(path.join(webAssets,key+'.png'),png);
  await fs.writeFile(path.join(appAssets,key+'.png'),png);
}
await fs.writeFile(path.join(mobile,'lib/shared/service_icon_presets.dart'),
  '// Generated by frondend/tools/sync-service-icons.mjs.\n'
  + 'const servicePresetKeys = <String>{'+serviceIconPresets.map(p=>JSON.stringify(p.key)).join(',')+'};\n'
  + 'const servicePresetAliases = <String,String>'+JSON.stringify(automaticIconKeys)+';\n'
  + 'String servicePresetKey(String key) => servicePresetKeys.contains(key) ? key : servicePresetAliases[key] ?? "grid";\n');
await fs.copyFile(require.resolve('lucide-react/LICENSE'),path.join(appAssets,'LICENSE-lucide.txt'));
console.log('Synced '+serviceIconPresets.length+' identical service icons for Admin and Customer.');

const webCategories=path.join(root,'public/category-icons'), appCategories=path.join(mobile,'assets/category-icons');
await fs.mkdir(webCategories,{recursive:true});await fs.mkdir(appCategories,{recursive:true});
for(const {key} of serviceIconPresets){
 const svg=renderToStaticMarkup(React.createElement(icons[names[key]],{size:160,color:'#DA5687',strokeWidth:2.4}));
 const png=await sharp(Buffer.from(svg)).png().toBuffer();
 await fs.writeFile(path.join(webCategories,key+'.png'),png);await fs.writeFile(path.join(appCategories,key+'.png'),png);
}
await fs.copyFile(require.resolve('lucide-react/LICENSE'),path.join(appCategories,'LICENSE-lucide.txt'));
